export function getNodePins(node: { type: ComponentType; bitWidth?: BitWidth; portName?: string }) {
  const def = COMPONENT_DEFS[node.type];
  if (node.type === 'PORT_IN') {
    const w = node.bitWidth ?? 1;
    return {
      inputs: [] as PinDef[],
      outputs: [p('OUT', node.portName ?? 'IN', w, 'right', `ورودی ${node.portName ?? ''} (${w} بیتی)`)],
    };
  }
  if (node.type === 'PORT_OUT') {
    const w = node.bitWidth ?? 1;
    return {
      inputs: [p('IN', node.portName ?? 'OUT', w, 'left', `خروجی ${node.portName ?? ''} (${w} بیتی)`)],
      outputs: [] as PinDef[],
    };
  }
  return { inputs: def.inputs, outputs: def.outputs };
}

export function getNodeHeight(node: { type: ComponentType; bitWidth?: BitWidth; portName?: string }): number {
  const def = COMPONENT_DEFS[node.type];
  const { inputs, outputs } = getNodePins(node);
  const maxPins = Math.max(inputs.length, outputs.length, 1);
  const computed = 44 + maxPins * 22;
  return Math.max(def.minHeight ?? 60, computed);
}

export function getPinOffset(
  node: { type: ComponentType; bitWidth?: BitWidth; portName?: string },
  pinId: string,
  side: 'left' | 'right'
): { dx: number; dy: number } {
  const def = COMPONENT_DEFS[node.type];
  const h = getNodeHeight(node);
  const { inputs, outputs } = getNodePins(node);
  const list = side === 'left' ? inputs : outputs;
  const idx = Math.max(
    0,
    list.findIndex((item) => item.id === pinId)
  );
  const topPad = 36;
  const usable = h - topPad - 10;
  const step = usable / Math.max(list.length, 1);
  const dy = topPad + step * idx + step / 2;
  const dx = side === 'left' ? 0 : def.width;
  return { dx, dy };
}
